const byNumeric = new Map(WORLD_COUNTRIES.map((row) => [row.numeric, row]));
const byCode = new Map(
  WORLD_COUNTRIES.map((row) => [String(row.code).toUpperCase(), row])
);

function listWorldCountriesDropdown() {
  return [...WORLD_COUNTRIES]
    .sort((a, b) => a.name.localeCompare(b.name))
    .map((row) => ({
      value: row.numeric,
      label: row.name,
      code: row.code
    }));
}

function resolveWorldCountry(input) {
  if (input == null || input === "") {
    return null;
  }

  if (typeof input === "string" && /^[A-Za-z]{2}$/.test(input.trim())) {
    return byCode.get(input.trim().toUpperCase()) ?? null;
  }

  const numeric = Number(input);
  if (Number.isFinite(numeric)) {
    return byNumeric.get(numeric) ?? null;
  }

  return null;
}

